static int g_pass, g_fail;

static void t_pass(const char *name)
{
	g_pass++;
	printf("PASS  %s\n", name);
}

static void t_fail(const char *name, const char *detail)
{
	g_fail++;
	printf("FAIL  %s :: %s\n", name, detail);
}

static const char *roots[] = { "tests/unit/vectors/", "vectors/" };

static uint8_t *read_vec(const char *name, size_t *n_out)
{
	unsigned r;
	for (r = 0u; r < 2u; r++) {
		char path[256];
		FILE *f;
		uint8_t *b;
		long n;
		snprintf(path, sizeof path, "%s%s", roots[r], name);
		f = fopen(path, "rb");
		if (f == NULL)
			continue;
		if (fseek(f, 0, SEEK_END) != 0) {
			fclose(f);
			continue;
		}
		n = ftell(f);
		if (n <= 0 || n > 1048576) {
			fclose(f);
			continue;
		}
		rewind(f);
		b = (uint8_t *)malloc((size_t)n);
		if (b == NULL) {
			fclose(f);
			continue;
		}
		if (fread(b, 1, (size_t)n, f) != (size_t)n) {
			free(b);
			fclose(f);
			continue;
		}
		fclose(f);
		*n_out = (size_t)n;
		return b;
	}
	return NULL;
}

