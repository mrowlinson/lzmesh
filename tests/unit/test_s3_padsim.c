static void one_case_sel(const char *vec, const uint8_t *want, size_t want_n,
    const char *name, unsigned sel)
{
	uint8_t *in;
	size_t in_n = 0u;
	uint8_t *dst;
	uint8_t *scratch;
	size_t cap, ssz, n;
	in = read_vec(vec, &in_n);
	if (in == NULL) {
		t_fail(name, "fixture missing");
		return;
	}
	cap = in_n + 4096u;
	dst = (uint8_t *)malloc(cap);
	ssz = lzmesh_encode_scratch_size(sel);
	scratch = (uint8_t *)malloc(ssz != 0u ? ssz : 1u);
	if (dst == NULL || scratch == NULL) {
		t_fail(name, "oom");
		free(in);
		free(dst);
		free(scratch);
		return;
	}
	n = lzmesh_encode(dst, cap, in, in_n, scratch, sel);
	if (n != want_n) {
		char d[96];
		snprintf(d, sizeof d, "outlen %lu want %lu",
		    (unsigned long)n, (unsigned long)want_n);
		t_fail(name, d);
	} else if (memcmp(dst, want, want_n) != 0) {
		size_t j = 0u;
		while (j < want_n && dst[j] == want[j])
			j++;
		{
			char d[96];
			snprintf(d, sizeof d, "first diff at byte %lu",
			    (unsigned long)j);
			t_fail(name, d);
		}
	} else {
		t_pass(name);
	}
	free(in);
	free(dst);
	free(scratch);
}

static void one_case(const char *vec, const uint8_t *want, size_t want_n,
    const char *name)
{
	one_case_sel(vec, want, want_n, name, 0xe05);
}
static void one_case_file(const char *vec, const char *wantfile,
    const char *name)
{
	uint8_t *want;
	size_t want_n = 0u;
	want = read_vec(wantfile, &want_n);
	if (want == NULL) {
		t_fail(name, "want fixture missing");
		return;
	}
	one_case(vec, want, want_n, name);
	free(want);
}
static void one_case_file_sel(const char *vec, const char *wantfile,
    const char *name, unsigned sel)
{
	uint8_t *want;
	size_t want_n = 0u;
	want = read_vec(wantfile, &want_n);
	if (want == NULL) {
		t_fail(name, "want fixture missing");
		return;
	}
	one_case_sel(vec, want, want_n, name, sel);
	free(want);
}

