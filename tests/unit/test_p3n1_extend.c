static void run_one(int v, int l)
{
	char name[64], detail[160];
	static uint8_t in[2048], enc[8192], enc2[8192], dec[2048];
	size_t n = 0, eret, eret2, ds, dret, xlen;
	const uint8_t *xp;

	snprintf(name, sizeof(name), "p3n1 v%d %s", v, LNAMES[l]);
	fill(v, in, &n);
	eret = lzmesh_encode(enc, sizeof(enc), in, n, NULL, LEVELS[l]);
	if (eret == 0 || eret > sizeof(enc)) {
		snprintf(detail, sizeof(detail), "encode returned %lu",
			 (unsigned long)eret);
		t_fail(name, detail);
		return;
	}
	xp = fx_ptr(v, l, &xlen);
	if (xp == NULL || eret != xlen || memcmp(enc, xp, eret) != 0) {
		snprintf(detail, sizeof(detail), "fixture diff: got %lu want %lu",
			 (unsigned long)eret, (unsigned long)xlen);
		t_fail(name, detail);
		return;
	}
	eret2 = lzmesh_encode(enc2, sizeof(enc2), in, n, NULL, LEVELS[l]);
	if (eret2 != eret || memcmp(enc2, enc, eret) != 0) {
		t_fail(name, "nondeterministic encode");
		return;
	}
	ds = lzmesh_decoded_size(enc, eret);
	dret = lzmesh_decode(dec, sizeof(dec), enc, eret, NULL);
	if (ds != n || dret != n || memcmp(dec, in, n) != 0) {
		t_fail(name, "roundtrip mismatch");
		return;
	}
	t_pass(name);
}

