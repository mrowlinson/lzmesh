{
	int v, l;
	for (v = 0; v <= 8; v++)
		for (l = 0; l < 4; l++)
			run_one(v, l);
	printf("p3n1_extend: %d pass %d fail\n", g_pass, g_fail);
	return g_fail != 0;
}
